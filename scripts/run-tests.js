// Runs the five test samples through the app and writes the before/after report.
// Usage: node scripts/run-tests.js [base-url]     (default http://localhost:3311)
// Needs the app running with a real API key (npm run dev) or a deployed URL.
import { readFileSync, writeFileSync } from "node:fs";

const base = (process.argv[2] || "http://localhost:3311").replace(/\/$/, "");
const passcode = process.env.APP_PASSCODE || "";
const samples = JSON.parse(readFileSync("app/samples.json", "utf8"));
const results = [];

for (const s of samples) {
  process.stdout.write(`${s.label}... `);
  const res = await fetch(`${base}/api/rewrite`, {
    method: "POST",
    headers: { "Content-Type": "application/json", "x-passcode": passcode },
    body: JSON.stringify({ text: s.text }),
  });
  const data = await res.json();
  if (!res.ok) throw new Error(`${s.label}: ${data.error}`);
  results.push({ label: s.label, original: s.text, ...data });
  console.log(`${data.before.total} → ${data.after.total} tells, ${data.seconds}s`);
}

writeFileSync("docs/test-report/results.json", JSON.stringify({ ranAt: new Date().toISOString(), base, results }, null, 2) + "\n");

const fmtPatterns = (bp) => Object.entries(bp).map(([k, v]) => `${k} ×${v}`).join(", ") || "none";
const quote = (t) => t.split("\n").map((l) => `> ${l}`).join("\n");
let md = `# Test results: before and after\n\nGenerated by \`scripts/run-tests.js\` on ${new Date().toISOString().slice(0, 10)} against ${base}. Model: ${results[0]?.model}. Originals are unedited Claude output (see samples-original.md for the prompts).\n\n`;
md += `| Sample | Words before → after | AI tells before → after | Per 100 words | Changes made | Second pass needed |\n|---|---|---|---|---|---|\n`;
for (const r of results) {
  md += `| ${r.label} | ${r.before.words} → ${r.after.words} | ${r.before.total} → ${r.after.total} | ${r.before.per100} → ${r.after.per100} | ${r.changes.length} | ${r.repaired ? "yes" : "no"} |\n`;
}
for (const r of results) {
  md += `\n## ${r.label}\n\n**Tells found before:** ${fmtPatterns(r.before.byPattern)}\n\n**Tells left after:** ${fmtPatterns(r.after.byPattern)}\n\n### Before\n\n${quote(r.original)}\n\n### After\n\n${quote(r.rewrite)}\n\n### What changed\n\n`;
  md += r.changes.map((c, i) => `${i + 1}. \`${c.pattern}\`: "${c.before}" → ${c.after ? `"${c.after}"` : "removed"}. ${c.why}`).join("\n") + "\n";
  if (r.kept.length) md += `\n### Left alone\n\n` + r.kept.map((k) => `- "${k.text}": ${k.why}`).join("\n") + "\n";
}
writeFileSync("docs/test-report/results.md", md);
console.log("Wrote docs/test-report/results.md and results.json");
