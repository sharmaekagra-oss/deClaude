// Runs the five test samples through the app and writes the before/after report.
// Usage: node scripts/run-tests.js [base-url] [--fresh]     (default http://localhost:3311)
// Needs the app running with a real API key (npm run dev) or a deployed URL.
// Saves after every sample and skips samples already done against the same URL, so a failed
// run can be resumed. --fresh starts over.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import http from "node:http";
import https from "node:https";

const args = process.argv.slice(2);
const fresh = args.includes("--fresh");
const base = (args.find((a) => !a.startsWith("--")) || "http://localhost:3311").replace(/\/$/, "");
const passcode = process.env.APP_PASSCODE || "";
const samples = JSON.parse(readFileSync("app/samples.json", "utf8"));
const OUT = "docs/test-report/results.json";

// Plain http(s) request with no client-side timeout: free-tier rewrites can take minutes.
function post(url, body) {
  const u = new URL(url);
  const lib = u.protocol === "https:" ? https : http;
  return new Promise((resolve, reject) => {
    const req = lib.request(u, { method: "POST", headers: { "Content-Type": "application/json", "x-passcode": passcode } }, (res) => {
      let raw = "";
      res.setEncoding("utf8");
      res.on("data", (c) => (raw += c));
      res.on("end", () => {
        try { resolve({ status: res.statusCode, data: JSON.parse(raw) }); }
        catch { reject(new Error(`Non-JSON reply (${res.statusCode}): ${raw.slice(0, 200)}`)); }
      });
    });
    req.on("error", reject);
    req.end(JSON.stringify(body));
  });
}

let saved = { base, results: [] };
if (!fresh && existsSync(OUT)) {
  const prev = JSON.parse(readFileSync(OUT, "utf8"));
  if (prev.base === base) saved = prev;
}
const done = new Set(saved.results.map((r) => r.label));

for (const s of samples) {
  if (done.has(s.label)) { console.log(`${s.label}: already done, skipping`); continue; }
  process.stdout.write(`${s.label}... `);
  let status, data;
  for (let attempt = 1; ; attempt++) {
    ({ status, data } = await post(`${base}/api/rewrite`, { text: s.text }));
    // 503 = overloaded, 429 = free-tier per-minute limit. Both usually clear within a minute.
    // (A used-up daily quota also returns 429; that fails after three tries.)
    if (![429, 503].includes(status) || data.daily || attempt > 3) break;
    process.stdout.write(`${status === 429 ? "rate-limited" : "overloaded"}, retrying in 60s (${attempt}/3)... `);
    await new Promise((r) => setTimeout(r, 60_000));
  }
  if (status !== 200) throw new Error(`${s.label}: ${data.error}`);
  saved.results.push({ label: s.label, original: s.text, ...data });
  saved.ranAt = new Date().toISOString();
  writeFileSync(OUT, JSON.stringify(saved, null, 2) + "\n");
  console.log(`${data.before.total} → ${data.after.total} tells, ${data.seconds}s`);
}

// Report in the samples' order
const results = samples.map((s) => saved.results.find((r) => r.label === s.label)).filter(Boolean);
const providers = [...new Set(results.map((r) => (r.provider === "gemini" ? "Google Gemini (free tier)" : "Anthropic Claude")))];
const fmtPatterns = (bp) => Object.entries(bp).map(([k, v]) => `${k} ×${v}`).join(", ") || "none";
const quote = (t) => t.split("\n").map((l) => `> ${l}`).join("\n");
let md = `# Test results: before and after\n\nGenerated by \`scripts/run-tests.js\` on ${saved.ranAt.slice(0, 10)} against ${base}. Provider: ${providers.join(", ")}. Model: ${[...new Set(results.map((r) => r.model))].join(", ")}. Originals are unedited Claude output (see samples-original.md for the prompts).\n\n`;
md += `| Sample | Words before → after | AI tells before → after | Per 100 words | Changes made | Second pass needed | Time |\n|---|---|---|---|---|---|---|\n`;
for (const r of results) {
  md += `| ${r.label} | ${r.before.words} → ${r.after.words} | ${r.before.total} → ${r.after.total} | ${r.before.per100} → ${r.after.per100} | ${r.changes.length} | ${r.repaired ? "yes" : "no"} | ${r.seconds}s |\n`;
}
for (const r of results) {
  md += `\n## ${r.label}\n\n**Tells found before:** ${fmtPatterns(r.before.byPattern)}\n\n**Tells left after:** ${fmtPatterns(r.after.byPattern)}\n\n### Before\n\n${quote(r.original)}\n\n### After\n\n${quote(r.rewrite)}\n\n### What changed\n\n`;
  md += r.changes.map((c, i) => `${i + 1}. \`${c.pattern}\`: "${c.before}" → ${c.after ? `"${c.after}"` : "removed"}. ${c.why}`).join("\n") + "\n";
  if (r.kept.length) md += `\n### Left alone\n\n` + r.kept.map((k) => `- "${k.text}": ${k.why}`).join("\n") + "\n";
}
writeFileSync("docs/test-report/results.md", md);
console.log(`Wrote docs/test-report/results.md and results.json (${results.length}/${samples.length} samples)`);
