// Builds docs/test-report/REPORT.md, the test report for submission, from the saved data:
// samples-original.md (prompts), results.json (official run), detectors.md, blind-test/results.md.
// Re-run after the blind test: node scripts/build-report.js
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const read = (p) => readFileSync(p, "utf8").replace(/\r\n/g, "\n");
const { ranAt, results } = JSON.parse(read("docs/test-report/results.json"));
const samplesMd = read("docs/test-report/samples-original.md");
const prompts = Object.fromEntries(samplesMd.split(/^## /m).slice(1).map((part) => {
  const [head, ...rest] = part.split("\n");
  const prompt = (rest.join("\n").match(/^\*\*Prompt:\*\*\s*(.+)$/m) || [])[1] || "";
  return [head.replace(/^\d+\.\s*/, "").trim(), prompt];
}));
const order = ["Email", "Blog post", "Product description", "LinkedIn post", "Cover letter"];
const rows = order.map((l) => results.find((r) => r.label === l)).filter(Boolean);
const model = [...new Set(rows.map((r) => r.model))].join(", ");
const sum = (f) => rows.reduce((a, r) => a + f(r), 0);
const quote = (t) => t.split("\n").map((l) => `> ${l}`).join("\n");
const pats = (bp) => Object.entries(bp).map(([k, v]) => `\`${k}\` ×${v}`).join(", ") || "none";

// What reading each rewrite by hand found. Written by the team after checking every fact.
const REVIEW = {
  "Email": "All facts kept: the reason (new client requirements), Friday, next Wednesday, the progress update. Added one line the writer never wrote: \"I appreciate your flexibility.\" Its \"Your turn\" questions were weak (about Wednesday timing, not the writer's own detail).",
  "Blog post": "All five bold lead-ins removed; every argument kept. \"But this math only holds once.\" became \"But this only works once.\" (the dropped-sentence check flagged it; no content was lost). The title is still in Title Case. The repair pass was skipped because the free model was busy.",
  "Product description": "Every spec, the care line and the price kept. Lost one list item: \"backpack, gym bag, or laptop sleeve\" became \"backpack or gym bag\".",
  "LinkedIn post": "Bold labels, hashtags, \"Looking forward to what year two brings\" and the closing engagement question removed. One \"X, not Y\" survives as \"Frameworks are a starting point; they are not the answer.\"",
  "Cover letter": "All facts kept: \"planned and ran\", 40%, the lesson about data-driven adjustments, Pink Friday. The writer's contractions were expanded (\"I'm\" to \"I am\"), so it reads more formal than the original; the app flagged this.",
};

const detectors = read("docs/test-report/detectors.md");
const tablesOnly = detectors.split("\n").filter((l) => l.startsWith("|") || l.startsWith("##") || l.startsWith("\\*")).join("\n");
const blind = existsSync("docs/blind-test/results.md") ? read("docs/blind-test/results.md").replace(/^# .+\n/, "") : null;

let md = `# deClaude: test report

Group 1 · MICA OpenProject · Aakansha Johari, Shivam Singh, Akshat Jha, Eishita Mehta, Ekagra Sharma

App: https://declaude-nine.vercel.app · Code: https://github.com/sharmaekagra-oss/deClaude

## 1. Summary

- We rewrote five pieces of Claude-written content (an email, a blog post, a product description, a LinkedIn post and a cover letter) with the deClaude app.
- **AI tells found by our scan fell from ${sum((r) => r.before.total)} to ${sum((r) => r.after.total)}**, and the text got ${Math.round(100 - (sum((r) => r.after.words) / sum((r) => r.before.words)) * 100)}% shorter overall.
- **Reading every rewrite by hand:** all key facts survived, except one list item (\"laptop sleeve\"). One rewrite added a polite line the writer never wrote.
- **AI detectors were not fooled.** GPTZero called every text it scanned 100% AI, rewrites included. Sapling's scores swung from 99.5% to 0% on near-identical text.
- **Blind test with classmates:** ${blind ? "see section 6." : "not yet run; section 6 describes the design. This report will be regenerated with real results."}

## 2. Method

**Test pieces.** Five pieces generated by Claude (Opus 5.5) from plain prompts, with an instruction to write in its normal style and nothing about AI tells. The prompts:

${order.map((l) => `- **${l}:** ${prompts[l] || "(see samples-original.md)"}`).join("\n")}

**The app run.** All five pieces went through the live app's code on ${ranAt.slice(0, 10)}, on one fixed model so results are comparable: ${model} via Groq's free tier. The rewrite follows \`skill/SKILL.md\`.

**How we judged the rewrites.**
1. **AI-tell count:** the app's rule-based scan for our 24 patterns, before and after.
2. **Automatic fact checks:** lost numbers, source sentences with no counterpart in the rewrite, and lost contractions.
3. **Reading by hand:** a teammate read each rewrite against its original, fact by fact. The tell count can't see lost facts, so this step decides.
4. **AI detectors:** GPTZero and Sapling (free versions). See section 5.
5. **Blind test:** classmates guess which pieces were AI-written. See section 6.

## 3. Results

| Piece | AI tells before → after | Words before → after | Edits | Time |
|---|---|---|---|---|
${rows.map((r) => `| ${r.label} | ${r.before.total} → ${r.after.total} | ${r.before.words} → ${r.after.words} | ${r.changes.length} | ${r.seconds}s |`).join("\n")}
| **Total** | **${sum((r) => r.before.total)} → ${sum((r) => r.after.total)}** | **${sum((r) => r.before.words)} → ${sum((r) => r.after.words)}** | ${sum((r) => r.changes.length)} | |

**Which tells were in Claude's drafts:** ${(() => { const t = {}; rows.forEach((r) => Object.entries(r.before.byPattern).forEach(([k, v]) => (t[k] = (t[k] || 0) + v))); return Object.entries(t).sort((a, b) => b[1] - a[1]).map(([k, v]) => `\`${k}\` ${v}`).join(", "); })()}. None were "AI vocabulary" (delve, tapestry and so on). Claude's tells today are structural.

### Human review

| Piece | What reading it by hand found |
|---|---|
${rows.map((r) => `| ${r.label} | ${REVIEW[r.label]} |`).join("\n")}

## 4. Before and after

${rows.map((r) => `### ${r.label}

**Tells before:** ${pats(r.before.byPattern)} · **after:** ${pats(r.after.byPattern)}

**Before (Claude):**

${quote(r.original)}

**After (deClaude):**

${quote(r.rewrite)}

**What changed:**

${r.changes.map((c, i) => `${i + 1}. \`${c.pattern}\`: "${c.before}" → ${c.after ? `"${c.after}"` : "cut"}. ${c.why}`).join("\n")}
${(r.yourTurn || []).length ? `\n**"Your turn" questions the app asked the writer:** ${r.yourTurn.map((y) => `"${y.ask}"`).join(" · ")}\n` : ""}`).join("\n")}
## 5. AI detectors

${tablesOnly}

**What this means.** A style rewrite by a language model makes text read better, but strong detectors still flag it. This matches the research we did first: a published blind test of blader/humanizer (56k GitHub stars) found readers preferred its rewrites 16 times out of 16, while detection only fell from 100% to 98.6%. We chose not to add detector-evasion tricks (invisible characters, planted typos), because they make text worse and exist mainly to pass off AI writing as human. The app instead ends with "Your turn": questions that only the writer can answer, since the writer's own detail is what no model can supply.

## 6. Blind test

${blind || `**Status: not yet run.** No numbers appear here until real classmates have responded; we will not estimate or simulate them.

**Design** (full protocol in \`docs/blind-test/PROTOCOL.md\`):
- Three versions of each piece: Claude's original (O), the deClaude rewrite (R), and a version teammates write themselves without AI (H).
- Two forms, so nobody reads two versions of the same piece. Each classmate reads 10 short pieces and answers: written by a person or by AI, and how sure (1 to 5), plus what gave it away.
- At least 5 classmates, ideally 10 or more.
- **Success would look like:** rewrites called "AI" noticeably less often than originals, and close to the human-written pieces.`}

## 7. Limitations

- **Small sample.** Five pieces, one of each type, all from one model and one set of prompts.
- **Our tell count is our own scan.** It measures the 24 patterns we chose; it can't see lost facts, and a short reworded sentence can trip the dropped-sentence check.
- **Free models cut corners.** On the free tier the second "repair" pass is sometimes skipped when the model is busy, and fast models occasionally drop a list item or add a line. We read every rewrite by hand for this reason.
- **Detector testing was limited** to free tools without accounts: GPTZero stopped after 5 scans, QuillBot required a sign-up, and Sapling proved unstable.
- **English-tuned.** The pattern detectors are built for English; other languages are rewritten but not scored well.

## 8. Earlier runs

We ran the five pieces several times while building the app. A low tell count never settled it; reading the rewrites did, and each problem found led to a fix:
- **Gemini (gemini-3.5-flash), 13 October:** 32 → 7 tells, the same low count as today, but it cut the cover letter's "biggest lesson", turned "planned and ran" into "ran", dropped list items from the product description and expanded most of the cover letter's contractions. This led to the fact and register checks and stricter SKILL.md rules.
- **Groq, 14 October, first attempt:** it dropped the email's reason for the delay and the product's care instructions. This led to the dropped-sentence check and SKILL.md rule 8. After the fix the same run scored 32 → 10 with those facts kept (archived as \`results-groq-gpt-oss-120b\`).
- **Groq, 15 October (this report):** 32 → ${sum((r) => r.after.total)} tells, after adding rules for varied rhythm and less predictable wording, plus the "Your turn" step.

Raw outputs of the archived runs are in \`docs/test-report/\`.
`;

writeFileSync("docs/test-report/REPORT.md", md);
